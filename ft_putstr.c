#include "ft_printf.h"

int	ft_putstr(char *s)
{
	int len;

	len = 0;
	if (!s)
		return (write (1, "(null)", 6));
	while (*s)
	{
		write(1, s, 1);
		s++;
		len++;
	}
	return (len);
}
