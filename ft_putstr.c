#include "ft_printf.h"

int	ft_putstr(char *s)
{
	int	len;

	len = 0;
	if (!s)
	{
		if ((write (1, "(null)", 6) == -1))
			return (-1);
		return (6);
	}
	while (*s)
	{
		if (write(1, s, 1) == -1)
			return (-1);
		s++;
		len++;
	}
	return (len);
}
